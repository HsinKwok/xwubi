-- 码表数据：字根表与例字库
-- 版本取值与站点一致：86 / 98 / xsj

CREATE TABLE IF NOT EXISTS wubi_roots (
  id TEXT PRIMARY KEY,
  version TEXT NOT NULL,
  key TEXT NOT NULL,
  mnemonic TEXT NOT NULL DEFAULT '',
  roots TEXT NOT NULL DEFAULT '',
  note TEXT,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_wubi_roots_version_key
  ON wubi_roots (version, key);

CREATE INDEX IF NOT EXISTS idx_wubi_roots_version_sort
  ON wubi_roots (version, sort_order);

CREATE TABLE IF NOT EXISTS wubi_examples (
  id TEXT PRIMARY KEY,
  version TEXT NOT NULL,
  char TEXT NOT NULL,
  code TEXT NOT NULL,
  roots TEXT NOT NULL DEFAULT '',
  note TEXT,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_wubi_examples_version_char
  ON wubi_examples (version, char);

CREATE INDEX IF NOT EXISTS idx_wubi_examples_version_sort
  ON wubi_examples (version, sort_order);

